// Set by the app so module-level helpers can follow the UI language.
let activeLang: Lang = 'en';
export const setActiveLang = (lang: Lang): void => { activeLang = lang; };
export const currentLang = (): Lang => activeLang;

export function apiErrorText(lang: Lang, message: string): string {
  if (lang !== 'ko') return message;
  for (const [pattern, build] of koApiErrors) {
    const match = message.match(pattern);
    if (match) return build(match);
  }
  return koServerText(message);
}

/** Message lists from the server (file checks, skill findings) in the dashboard language. */
export const serverLines = (lines: readonly string[]): string[] => lines.map(line => apiErrorText(activeLang, line));

export function durationText(lang: Lang, ms: number): string {
  if (!Number.isFinite(ms) || ms < 0) return '-';
  const seconds = Math.round(ms / 1000);
  if (seconds < 60) return `${seconds} ${translate(lang, 'seconds')}`;
  return `${Math.floor(seconds / 60)} ${translate(lang, 'minutes')} ${seconds % 60} ${translate(lang, 'seconds')}`;
}

/** "2d 3h 5m" / "2일 3시간 5분"; zero units are left out, and under a minute still reads as 1 minute. */
export function remainingText(lang: Lang, totalMinutes: number): string {
  const minutes = Math.max(1, Math.round(totalMinutes));
  const days = Math.floor(minutes / 1440);
  const hours = Math.floor((minutes % 1440) / 60);
  const rest = minutes % 60;
  const unit = lang === 'ko' ? { d: '일', h: '시간', m: '분' } : { d: 'd', h: 'h', m: 'm' };
  return [days ? `${days}${unit.d}` : '', hours ? `${hours}${unit.h}` : '', rest || (!days && !hours) ? `${rest}${unit.m}` : ''].filter(Boolean).join(' ');
}

